import { createServer as createViteServer } from 'vite';
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';

const root = dirname(fileURLToPath(import.meta.url));
const analyzerName = process.platform === 'win32' ? 'analyzer.exe' : 'analyzer';
const analyzerPath = join(root, analyzerName);
const operations = new Set(['stats', 'bfs', 'dfs', 'shortest', 'dijkstra', 'allPaths', 'cycles', 'scc']);
let analyzerBuild;

async function ensureAnalyzer() {
  let analyzerTime = 0;
  try {
    analyzerTime = (await stat(analyzerPath)).mtimeMs;
  } catch {
  }
  const sourceTimes = await Promise.all(['main.cpp', 'Graph.cpp', 'Graph.h'].map(async (file) => (await stat(join(root, file))).mtimeMs));
  if (analyzerTime >= Math.max(...sourceTimes)) return;

  if (!analyzerBuild) {
    const command = process.platform === 'win32'
      ? `g++ -std=c++17 -O2 -Wall -Wextra main.cpp Graph.cpp -o analyzer.exe`
      : `g++ -std=c++17 -O2 -Wall -Wextra main.cpp Graph.cpp -o analyzer`;
    analyzerBuild = new Promise((resolvePromise, rejectPromise) => {
      const child = spawn(process.platform === 'win32' ? 'cmd.exe' : 'sh', process.platform === 'win32' ? ['/d', '/s', '/c', command] : ['-c', command], { cwd: root });
      child.on('error', rejectPromise);
      child.on('close', (code) => code === 0 ? resolvePromise() : rejectPromise(new Error(`Analyzer build failed with exit code ${code}`)));
    });
  }
  try {
    await analyzerBuild;
  } finally {
    analyzerBuild = undefined;
  }
}

async function runAnalyzer(operation, transactions, source, destination) {
  await ensureAnalyzer();
  const tempDirectory = join(root, '.ctga-temp', randomUUID());
  const inputPath = join(tempDirectory, 'transactions.txt');
  await mkdir(tempDirectory, { recursive: true });
  const payload = transactions.map((tx) => `${tx.sender} ${tx.receiver} ${tx.amount}`).join('\n');
  await writeFile(inputPath, `# Generated by CTGA frontend\n${payload}\n`, 'utf8');
  const args = [inputPath, `--operation=${operation}`];
  if (source) args.push(`--source=${source}`);
  if (destination) args.push(`--destination=${destination}`);
  return new Promise((resolvePromise, rejectPromise) => {
    const child = spawn(analyzerPath, args, { cwd: root });
    let stdout = '', stderr = '';
    child.stdout.on('data', (chunk) => { stdout += chunk; });
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.on('error', rejectPromise);
    child.on('close', async (code) => {
      if (code !== 0) return rejectPromise(new Error(stderr.trim() || `Analyzer exited with code ${code}`));
      try { resolvePromise(JSON.parse(stdout)); }
      catch { rejectPromise(new Error(`Invalid analyzer response: ${stdout}`)); }
    });
  }).finally(() => rm(tempDirectory, { recursive: true, force: true }));
}

const vite = await createViteServer({ root, server: { port: 5173 }, appType: 'custom' });
vite.middlewares.use('/api/analyze', async (request, response, next) => {
  if (request.method !== 'POST') {
    response.writeHead(405, { 'Content-Type': 'application/json' });
    response.end(JSON.stringify({ error: 'Method not allowed' }));
    return;
  }
  try {
    const chunks = [];
    for await (const chunk of request) chunks.push(chunk);
    const parsed = JSON.parse(Buffer.concat(chunks).toString() || '{}');
    if (!parsed || !operations.has(parsed.operation)) throw Object.assign(new Error('Unsupported analysis operation.'), { statusCode: 400 });
    if (!Array.isArray(parsed.transactions)) throw Object.assign(new Error('Transactions must be an array.'), { statusCode: 400 });
    const validAddress = (value) => typeof value === 'string' && value.length > 0 && !/[\s#]/.test(value);
    for (const transaction of parsed.transactions) {
      if (!transaction || !validAddress(transaction.sender) || !validAddress(transaction.receiver)
        || typeof transaction.amount !== 'number' || !Number.isFinite(transaction.amount) || transaction.amount <= 0) {
        throw Object.assign(new Error('Each transaction must have valid sender and receiver addresses and a positive amount.'), { statusCode: 400 });
      }
    }
    for (const field of ['source', 'destination']) {
      if (parsed[field] !== undefined && parsed[field] !== '' && !validAddress(parsed[field])) {
        throw Object.assign(new Error(`${field} must be a valid address.`), { statusCode: 400 });
      }
    }
    const result = await runAnalyzer(parsed.operation, parsed.transactions, parsed.source || '', parsed.destination || '');
    response.writeHead(200, { 'Content-Type': 'application/json' });
    response.end(JSON.stringify(result));
  } catch (error) {
    response.writeHead(error.statusCode || 500, { 'Content-Type': 'application/json' });
    response.end(JSON.stringify({ error: error.message || 'The graph analyzer failed.' }));
  }
});
vite.middlewares.use(async (request, response, next) => {
  if (request.method !== 'GET' || !request.headers.accept?.includes('text/html')) {
    next();
    return;
  }
  try {
    const html = await vite.transformIndexHtml(request.url || '/', await readFile(join(root, 'index.html'), 'utf8'));
    response.writeHead(200, { 'Content-Type': 'text/html' });
    response.end(html);
  } catch (error) {
    next(error);
  }
});
await vite.listen();
const port = vite.config.server.port || 5173;
console.log(`CTGA frontend running at http://localhost:${port}`);
